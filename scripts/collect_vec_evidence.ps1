<#
.SYNOPSIS
    Collects the evidence that the simd build is vectorised and the scalar one is not.

.DESCRIPTION
    For each build variant (scalar: build/, simd: build/simd/) this script
      1. reads the exact compiler flags from <variant>/build_info.h, so the
         evidence always matches what build.ps1 actually used;
      2. recompiles the kernel units (matmul_seq.c, matmul_omp.c) with those
         flags plus -fopt-info-vec-all to obtain gcc's vectoriser report;
      3. disassembles the kernel objects produced by build.ps1 with objdump;
      4. counts the double-precision multiply/add instructions by kind
         (256-bit packed, 128-bit packed, scalar, FMA).
    It also records what -march=native resolves to on this machine and the
    effective -ffp-contract setting, and checks with test.exe --dump that both
    variants compute bitwise-identical products (SHA-256 of the dumped C).

    Output: results/vectorisation_evidence/ (summary.txt, opt_info_*.txt,
    disasm_*.txt).

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File build.ps1
    powershell -NoProfile -ExecutionPolicy Bypass -File build.ps1 -Variant simd
    powershell -NoProfile -ExecutionPolicy Bypass -File scripts/collect_vec_evidence.ps1
#>
param(
    [string]$GccDir = "C:\msys64\ucrt64\bin",
    [int[]]$DumpSizes = @(257, 512, 1024),
    [int]$DumpThreads = 8,
    [UInt64]$DumpSeed = 20250301
)

$ErrorActionPreference = "Stop"
$Root    = Split-Path -Parent $PSScriptRoot
$OutDir  = Join-Path $Root "results\vectorisation_evidence"
$Gcc     = Join-Path $GccDir "gcc.exe"
$Objdump = Join-Path $GccDir "objdump.exe"
foreach ($tool in @($Gcc, $Objdump)) {
    if (-not (Test-Path $tool)) { throw "$tool not found (use -GccDir)" }
}
# gcc's helper programs (cc1, as) need their DLLs from the same directory.
$env:PATH = "$GccDir;$env:PATH"
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
$Tmp = Join-Path ([IO.Path]::GetTempPath()) "matmul_vec_evidence"
New-Item -ItemType Directory -Force -Path $Tmp | Out-Null

$Variants = [ordered]@{
    "scalar" = Join-Path $Root "build"
    "simd"   = Join-Path $Root "build\simd"
}
# Kernel units -> compiled with OpenMP?
$Kernels = [ordered]@{
    "matmul_seq.c" = $false
    "matmul_omp.c" = $true
}

# Runs a native tool and returns its output lines (stdout + stderr). Windows
# PowerShell 5.1 turns native stderr into errors, so the preference is relaxed
# locally and failures are detected through the exit code instead.
function Invoke-Tool([string]$exe, [string[]]$toolArgs) {
    $prev = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        $text = @(& $exe @toolArgs 2>&1 | ForEach-Object { "$_" })
    } finally {
        $ErrorActionPreference = $prev
    }
    if ($LASTEXITCODE -ne 0) {
        throw "$exe $($toolArgs -join ' ') failed ($LASTEXITCODE): $($text -join "`n")"
    }
    return ,$text
}

function Write-OutputFile([string]$path, [string[]]$lines) {
    [IO.File]::WriteAllLines($path, $lines)
}

function Get-BuildFlags([string]$dir) {
    $header = Join-Path $dir "build_info.h"
    if (-not (Test-Path $header)) {
        throw "$header not found; run build.ps1 for this variant first"
    }
    $text = Get-Content $header -Raw
    $cflags = [regex]::Match($text, '#define MATMUL_CFLAGS\s+"([^"]*)"').Groups[1].Value
    $omp = [regex]::Match($text, '#define MATMUL_OMP_FLAGS\s+"([^"]*)"').Groups[1].Value
    if (-not $cflags) { throw "MATMUL_CFLAGS not found in $header" }
    return @{ CFlags = @($cflags -split '\s+'); OmpFlags = @($omp -split '\s+' | Where-Object { $_ }) }
}

# Counts double-precision multiply/add instructions in an objdump listing
# (AT&T syntax, --no-show-raw-insn: "  addr:\tmnemonic operands").
function Get-InstructionCounts([string[]]$listing) {
    $counts = [ordered]@{ "packed256 (v{mul,add}pd ymm)" = 0; "packed128 ({mul,add}pd xmm)" = 0;
                          "scalar ({mul,add}sd)" = 0; "fma (vfmadd*/vfmsub*)" = 0 }
    foreach ($line in $listing) {
        $m = [regex]::Match($line, '^\s*[0-9a-f]+:\s+(\S+)\s*(.*)$')
        if (-not $m.Success) { continue }
        $mn = $m.Groups[1].Value
        $ops = $m.Groups[2].Value
        if ($mn -match '^vfn?m(add|sub)') { $counts["fma (vfmadd*/vfmsub*)"]++ }
        elseif ($mn -match '^v?(mul|add)pd$') {
            if ($ops -match '%ymm') { $counts["packed256 (v{mul,add}pd ymm)"]++ }
            else { $counts["packed128 ({mul,add}pd xmm)"]++ }
        }
        elseif ($mn -match '^v?(mul|add)sd$') { $counts["scalar ({mul,add}sd)"]++ }
    }
    return $counts
}

$summary = New-Object System.Collections.Generic.List[string]
$summary.Add("Vectorisation evidence (generated by scripts/collect_vec_evidence.ps1)")
$summary.Add("Date (UTC): $((Get-Date).ToUniversalTime().ToString('s'))Z")
$summary.Add("Compiler: gcc $((Invoke-Tool $Gcc @('-dumpfullversion'))[0])")
$summary.Add("")

# What -march=native means on this machine.
$target = Invoke-Tool $Gcc @("-march=native", "-Q", "--help=target")
$summary.Add("== -march=native resolves to ==")
foreach ($opt in @("-march=", "-mtune=", "-msse2", "-mavx", "-mavx2", "-mfma", "-mavx512f")) {
    # Exact option name followed by whitespace ("-mavx" must not match "-mavx2").
    $pattern = "^\s*$([regex]::Escape($opt))" + $(if ($opt.EndsWith("=")) { "" } else { "\s" })
    $hit = $target | Where-Object { $_ -match $pattern } | Select-Object -First 1
    if ($hit) { $summary.Add("  " + ($hit.Trim() -replace '\s+', ' ')) }
}
$summary.Add("")

# Floating-point contraction (FMA fusion) setting under -std=c11.
$opt = Invoke-Tool $Gcc @("-O3", "-std=c11", "-Q", "--help=optimize")
$fpc = $opt | Where-Object { $_ -match '-ffp-contract=' } | Select-Object -First 1
$summary.Add("== Floating-point contraction ==")
$summary.Add("  gcc -O3 -std=c11 -Q --help=optimize reports: " + ($fpc.Trim() -replace '\s+', ' '))
$summary.Add("  Note: -Q shows the language-independent default; for C in ISO mode (-std=c11)")
$summary.Add("  gcc documents -ffp-contract=off. The effective setting is checked below by")
$summary.Add("  counting FMA instructions in the simd objects, which are built with -mfma.")
$summary.Add("")
$simdFma = 0

foreach ($variant in $Variants.Keys) {
    $dir = $Variants[$variant]
    $flags = Get-BuildFlags $dir
    $summary.Add("== Variant '$variant' ($((Resolve-Path $dir).Path.Substring($Root.Length + 1))) ==")
    $summary.Add("  CFLAGS: $($flags.CFlags -join ' ')")
    foreach ($unit in $Kernels.Keys) {
        $base = [IO.Path]::GetFileNameWithoutExtension($unit)
        $unitFlags = @() + $flags.CFlags
        if ($Kernels[$unit]) { $unitFlags += $flags.OmpFlags }

        # 1. Vectoriser report (object written to a temporary directory).
        $reportTmp = Join-Path $Tmp "opt_info_${variant}_$base.txt"
        Remove-Item $reportTmp -ErrorAction SilentlyContinue
        $srcFile = Join-Path $Root "src\$unit"
        Invoke-Tool $Gcc ($unitFlags + @("-fopt-info-vec-all=$reportTmp", "-c", $srcFile,
                                         "-o", (Join-Path $Tmp "$base.o"))) | Out-Null
        $report = if (Test-Path $reportTmp) { @(Get-Content $reportTmp) } else { @() }
        $reportFile = Join-Path $OutDir "opt_info_${variant}_$base.txt"
        $hdr = @("# gcc $($unitFlags -join ' ') -fopt-info-vec-all -c src/$unit", "")
        Write-OutputFile $reportFile ([string[]]($hdr + $report))
        $vectorised = @($report | Where-Object { $_ -match 'loop vectorized' })

        # 2. Disassembly of the object that build.ps1 linked into bench.exe.
        $obj = Join-Path $dir "$base.o"
        if (-not (Test-Path $obj)) { throw "$obj not found; run build.ps1 for this variant first" }
        $listing = Invoke-Tool $Objdump @("-d", "--no-show-raw-insn", $obj)
        $disasmFile = Join-Path $OutDir "disasm_${variant}_$base.txt"
        Write-OutputFile $disasmFile ([string[]]$listing)
        $counts = Get-InstructionCounts $listing

        $summary.Add("  -- $unit")
        $summary.Add("     vectoriser: $($vectorised.Count) 'loop vectorized' message(s)")
        foreach ($v in $vectorised) {
            $summary.Add("       " + ($v -replace '^.*[\\/]src[\\/]', 'src/'))
        }
        foreach ($k in $counts.Keys) { $summary.Add(("     {0,-30} {1,5}" -f $k, $counts[$k])) }
        if ($variant -eq "simd") { $simdFma += $counts["fma (vfmadd*/vfmsub*)"] }
    }
    $summary.Add("")
}

$summary.Add("== Effective contraction ==")
if ($simdFma -eq 0) {
    $summary.Add("  0 FMA instructions in the simd kernels although -mfma is enabled:")
    $summary.Add("  a*b+c is not fused, so the simd build rounds exactly like the scalar one.")
} else {
    $summary.Add("  $simdFma FMA instruction(s) in the simd kernels: contraction is active and")
    $summary.Add("  results may differ from the scalar build in the last bits.")
}

$summary.Add("")

# Bitwise comparison of the products computed by both variants (test.exe --dump).
$summary.Add("== Scalar vs simd results (test.exe --dump, seed $DumpSeed, p = $DumpThreads) ==")
$allSame = $true
foreach ($n in $DumpSizes) {
    $hashes = @{}
    foreach ($variant in $Variants.Keys) {
        $exe = Join-Path $Variants[$variant] "test.exe"
        if (-not (Test-Path $exe)) { throw "$exe not found; run build.ps1 for this variant first" }
        $dumpDir = Join-Path $Tmp "dump_$variant"
        New-Item -ItemType Directory -Force -Path $dumpDir | Out-Null
        Invoke-Tool $exe @("--dump", "$n", "$DumpSeed", $dumpDir, "$DumpThreads") | Out-Null
        foreach ($name in @("C_seq_n${n}_s$DumpSeed.bin", "C_omp_p${DumpThreads}_n${n}_s$DumpSeed.bin")) {
            $file = Join-Path $dumpDir $name
            $hashes["$variant/$name"] = (Get-FileHash $file -Algorithm SHA256).Hash
        }
        Get-ChildItem $dumpDir -Filter "*.bin" | Remove-Item -Force
    }
    foreach ($kind in @("C_seq_n${n}_s$DumpSeed.bin", "C_omp_p${DumpThreads}_n${n}_s$DumpSeed.bin")) {
        $same = $hashes["scalar/$kind"] -eq $hashes["simd/$kind"]
        $allSame = $allSame -and $same
        $summary.Add(("  n={0,-5} {1,-28} scalar == simd (SHA-256): {2}" -f $n, $kind, $(if ($same) { "yes" } else { "NO" })))
    }
}
$summary.Add("  all identical: $(if ($allSame) { 'yes' } else { 'NO' })")

$summaryFile = Join-Path $OutDir "summary.txt"
Write-OutputFile $summaryFile ([string[]]$summary)
$summary | ForEach-Object { Write-Host $_ }
Write-Host "Evidence written to $OutDir"
if (-not $allSame) { exit 1 }
