<#
.SYNOPSIS
    Builds the matrix-multiplication kernels and programs with gcc (MSYS2 UCRT64).

.DESCRIPTION
    Primary build script (GNU make is not available on the benchmark machine;
    the Makefile mirrors these exact rules for POSIX systems).

    Every translation unit is compiled with the SAME optimisation flags
    ($CFlags). -fopenmp is added only where OpenMP is actually used
    (matmul_omp.c and the programs that call the OpenMP runtime API);
    matmul_seq.c and matmul_naive.c refuse to compile with it (#error).

    Outputs go to build/. build/build_info.h records the flags and compiler
    version so the benchmark can write them into every CSV row.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File build.ps1
    powershell -NoProfile -ExecutionPolicy Bypass -File build.ps1 -Target clean
#>
param(
    [ValidateSet("all", "clean")]
    [string]$Target = "all",
    [string]$GccDir = "C:\msys64\ucrt64\bin"
)

# "Continue": gcc warnings go to stderr, which must not abort the build in
# Windows PowerShell 5.1. Failures are detected through $LASTEXITCODE instead.
$ErrorActionPreference = "Continue"

$Root  = $PSScriptRoot
$Src   = Join-Path $Root "src"
$Build = Join-Path $Root "build"
$Gcc   = Join-Path $GccDir "gcc.exe"

# Main experiment flags: scalar code (no auto-vectorisation, no -march), so the
# thread-scaling study is not mixed with SIMD effects. See README.
$CFlags   = @("-O3", "-fno-tree-vectorize", "-std=c11", "-Wall", "-Wextra", "-Wpedantic")
$OmpFlags = @("-fopenmp")
# -static: executables embed libgomp/winpthreads, so they run without the
# MSYS2 bin directory on PATH and always use the runtime they were built with.
$LdLibs   = @("-static", "-lpsapi")

# Library objects: source file -> needs OpenMP?
$Units = [ordered]@{
    "matmul_seq.c"   = $false
    "matmul_naive.c" = $false
    "matmul_omp.c"   = $true
    "inputs.c"       = $false
    "timing.c"       = $false
    "affinity.c"     = $false
}

# Programs (built only if their source exists): main source -> executable.
$Programs = [ordered]@{
    "test.c"  = "test.exe"
    "bench.c" = "bench.exe"
}

function Invoke-Gcc([string[]]$GccArgs) {
    Write-Host ("gcc " + ($GccArgs -join " "))
    & $Gcc @GccArgs
    if ($LASTEXITCODE -ne 0) {
        Write-Error "gcc failed with exit code $LASTEXITCODE"
        exit 1
    }
}

if ($Target -eq "clean") {
    if (Test-Path $Build) {
        Get-ChildItem $Build -File | Where-Object { $_.Name -ne ".gitkeep" } | Remove-Item -Force
    }
    Write-Host "Cleaned $Build"
    exit 0
}

if (-not (Test-Path $Gcc)) {
    Write-Error "gcc not found at $Gcc (use -GccDir)"
    exit 1
}
# gcc's helper programs (cc1, as, ld) need their DLLs from the same directory.
$env:PATH = "$GccDir;$env:PATH"
New-Item -ItemType Directory -Force -Path $Build | Out-Null

# ------------------------------------------------------------ build_info.h
$gccVersion = (& $Gcc -dumpfullversion).Trim()
$buildInfo = @"
/* Generated by build.ps1 - do not edit. */
#ifndef BUILD_INFO_H
#define BUILD_INFO_H
#define MATMUL_COMPILER  "gcc $gccVersion"
#define MATMUL_CFLAGS    "$($CFlags -join ' ')"
#define MATMUL_OMP_FLAGS "$($OmpFlags -join ' ')"
#endif
"@
# ASCII without BOM so the C compiler reads it cleanly.
[IO.File]::WriteAllText((Join-Path $Build "build_info.h"), $buildInfo.Replace("`r`n", "`n"), [Text.Encoding]::ASCII)

# ------------------------------------------------------------ objects
$objects = @()
foreach ($unit in $Units.Keys) {
    $srcFile = Join-Path $Src $unit
    $objFile = Join-Path $Build ([IO.Path]::ChangeExtension($unit, ".o"))
    $flags = @() + $CFlags
    if ($Units[$unit]) { $flags += $OmpFlags }
    Invoke-Gcc ($flags + @("-c", $srcFile, "-o", $objFile))
    $objects += $objFile
}

# ------------------------------------------------------------ programs
foreach ($main in $Programs.Keys) {
    $srcFile = Join-Path $Src $main
    if (-not (Test-Path $srcFile)) {
        Write-Host "skip $main (not present yet)"
        continue
    }
    $exe = Join-Path $Build $Programs[$main]
    Invoke-Gcc ($CFlags + $OmpFlags + @("-I", $Build, $srcFile) + $objects + @("-o", $exe) + $LdLibs)
}

Write-Host "Build OK -> $Build"
